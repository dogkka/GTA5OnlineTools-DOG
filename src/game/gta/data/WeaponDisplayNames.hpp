	inline std::string_view GetWeaponDisplayNameFallback(joaat_t weaponHash)
	{
		const auto& fallbacks = GetWeaponNameFallbacks();
		if (const auto it = fallbacks.find(weaponHash); it != fallbacks.end())
			return it->second;

		return {};
	}
